/**
 * Proof, by execution, that this SDK covers the manifest.
 *
 * ═══ WHY THIS EXISTS ══════════════════════════════════════════════════════
 *
 * `packages/sdk-spec/surface.json` is the route list every Chatly backend SDK
 * implements, and the first thing built to enforce it searched each SDK's
 * source TEXT for the path strings. That is not a check on behaviour, and it
 * failed in both directions at once:
 *
 *   - Three SDKs scored 55/55 for routes they did not implement, because
 *     their authors had found two bogus manifest entries and written the
 *     paths into doc comments explaining the problem. The gate was loudest
 *     where somebody had done the careful thing.
 *   - A correct implementation can score 0 for a route it does implement:
 *     `self._get(f"/v1/{encode_path('teams', id)}/members")` never contains
 *     the literal `/v1/teams/`.
 *
 * So each SDK proves its own surface by CALLING every method against a
 * recording transport and writing down what went over the wire. A comment
 * cannot fake a request, and a helper-built path is recorded as what it
 * actually produced. The resulting `surface.lock.json` is a committed
 * artifact that `scripts/check-sdk-surface-parity.mjs` diffs against the
 * manifest, and it is regenerated by running the tests — not by a script
 * somebody has to remember.
 *
 * The declared shapes live in `test/surface-shapes.ts` and the calls in
 * `test/surface-invocations.ts`. They are separate files because the surface
 * went from 55 routes to 142 and this one would otherwise be ~950 lines; the
 * reason each table is hand-written rather than derived is in its own header.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { ChatlyClient } from './index.js';
import { invocations, walkers } from './test/surface-invocations.js';
import { EXPECTED_DISTRIBUTION, EXPECTED_SHAPE, type Shape } from './test/surface-shapes.js';

interface ManifestEntry {
  ns: string;
  name: string;
  http: string;
  path: string;
  shape?: Shape;
  paged?: boolean;
}

interface LockEntry {
  ns: string;
  name: string;
  http: string;
  path: string;
  shape: Shape;
}

/**
 * The manifest, in the monorepo or in a public mirror.
 *
 * `packages/sdk-spec/surface.json` here; a mirror has no `packages/` above the
 * package, so `scripts/sync-sdk-repos.mjs` vendors it at the mirror root. All
 * eight SDKs look in both places, because the mirror's own CI should prove the
 * same thing this suite does.
 */
function manifestPath(): string {
  const candidates = [
    join(__dirname, '../../sdk-spec/surface.json'),
    join(__dirname, '../sdk-spec/surface.json'),
  ];
  return candidates.find((p) => existsSync(p)) ?? candidates[0] ?? '';
}

const MANIFEST: { entries: ManifestEntry[] } = JSON.parse(readFileSync(manifestPath(), 'utf8')) as {
  entries: ManifestEntry[];
};

/** A success body of one shape, as the API would send it. */
function responseForShape(shape: Shape): Response {
  if (shape === 'empty') {
    // A real 204 has no body at all. A decoder that insists on parsing one
    // throws here, which is the point of giving this its own value.
    return new Response(null, { status: 204 });
  }
  const body =
    shape === 'page'
      ? '{"items":[{"id":"x_1"}],"nextCursor":null}'
      : shape === 'array'
        ? '[{"id":"x_1"}]'
        : '{"id":"x_1"}';
  return new Response(body, {
    status: 200,
    headers: { 'content-type': 'application/json' },
  });
}

/** The shape a decoded value actually has, named in the same vocabulary. */
function actualShape(value: unknown): string {
  if (value === undefined || value === null) {
    return 'empty';
  }
  if (Array.isArray(value)) {
    return 'array';
  }
  if (typeof value !== 'object') {
    return `scalar(${typeof value})`;
  }
  const o = value as Record<string, unknown>;
  return Array.isArray(o.items) && 'nextCursor' in o ? 'page' : 'object';
}

/**
 * Turn a concrete path back into the manifest's template.
 *
 * Replaces each throwaway argument with the manifest's own parameter name, by
 * POSITION — the manifest is the authority on what the parameters are called,
 * and this SDK's local names (`conversationId`, `teamId`) must not leak into
 * a cross-language artifact.
 */
function templatise(actual: string, template: string): string {
  const names = [...template.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
  const templateParts = template.split(/\{[^}]+\}/);
  if (names.length === 0) {
    return actual;
  }
  let rest = actual;
  let out = '';
  for (let i = 0; i < templateParts.length; i++) {
    const literal = templateParts[i] ?? '';
    if (!rest.startsWith(literal)) {
      // Shape disagrees with the template — return the raw path so the
      // assertion below reports the real difference rather than hiding it.
      return actual;
    }
    out += literal;
    rest = rest.slice(literal.length);
    if (i < names.length) {
      const nextLiteral = templateParts[i + 1] ?? '';
      const end = nextLiteral === '' ? rest.length : rest.indexOf(nextLiteral);
      if (end < 0) {
        return actual;
      }
      out += `{${String(names[i])}}`;
      rest = rest.slice(end);
    }
  }
  return out;
}

/** A client whose transport answers every call from `respond`. */
function clientAnswering(
  respond: () => Response,
  recorded: Array<{ method: string; path: string }>,
): ChatlyClient {
  const fetchFn = (async (url: string | URL, init?: RequestInit) => {
    recorded.push({
      method: init?.method ?? 'GET',
      path: new URL(String(url)).pathname,
    });
    return respond();
  }) as unknown as typeof fetch;

  return new ChatlyClient({
    apiKey: 'ck_surface_lock',
    apiUrl: 'https://api.test.invalid',
    fetchFn,
    retry: { attempts: 1 },
    sleepFn: async () => undefined,
  });
}

describe('surface lock', () => {
  it('declares a response shape for every entry, and all four shapes appear', () => {
    const calls = invocations(clientAnswering(() => responseForShape('object'), []));
    for (const { key } of calls) {
      expect(EXPECTED_SHAPE[key], `${key} has no declared response shape`).toBeDefined();
    }
    expect(Object.keys(EXPECTED_SHAPE).sort()).toEqual(calls.map((c) => c.key).sort());

    /*
     * Anti-vacuity. A column that said `object` 142 times would satisfy every
     * other assertion in this file and would still be worthless, so the
     * distribution is asserted. The numbers come from reading the handlers:
     * 31 array, 12 page, 98 object, 1 empty. If the surface grows these
     * change — but all four must stay represented, and `empty` must stay at
     * exactly one until a second 204 genuinely ships.
     */
    const counts = { array: 0, page: 0, object: 0, empty: 0 };
    for (const shape of Object.values(EXPECTED_SHAPE)) {
      counts[shape]++;
    }
    expect(counts).toEqual(EXPECTED_DISTRIBUTION);
  });

  it('issues exactly the request the manifest describes, for every entry', async () => {
    const byKey = new Map(MANIFEST.entries.map((e) => [`${e.ns}.${e.name}`, e]));

    /*
     * Floor on the audited set. A manifest that lost rows to a bad edit would
     * otherwise shrink this test silently and still pass unanimously — which
     * is the failure mode two other gates in this repo have already had.
     */
    expect(byKey.size, 'the manifest lost entries — check it parsed').toBeGreaterThanOrEqual(140);

    // Every manifest entry has an invocation, and no invocation is orphaned.
    const keys = invocations(clientAnswering(() => responseForShape('object'), [])).map(
      (c) => c.key,
    );
    expect(new Set(keys)).toEqual(new Set(byKey.keys()));

    const entries: LockEntry[] = [];
    for (const key of keys) {
      const entry = byKey.get(key);
      expect(entry, `no manifest entry for ${key}`).toBeDefined();
      const shape = EXPECTED_SHAPE[key] as Shape;

      /*
       * One client per route, answering with the shape THIS suite declares —
       * not a single fake answering everything with a page envelope, which is
       * how `macros.list` passed here and failed in production.
       */
      const recorded: Array<{ method: string; path: string }> = [];
      const chatly = clientAnswering(() => responseForShape(shape), recorded);
      const call = invocations(chatly).find((c) => c.key === key);
      expect(call, `invocation for ${key} vanished`).toBeDefined();

      const value = await (call as { call: () => Promise<unknown> }).call();

      expect(
        recorded,
        `${key} issued ${String(recorded.length)} requests, expected 1`,
      ).toHaveLength(1);

      /*
       * And the value handed back really has the declared shape.
       *
       * This is what catches a method that wraps or unwraps: a `list` that
       * returned `page.items` from a `page` route, or one that reached for
       * `.items` on a bare-array route, disagrees here even though the
       * request it issued was perfect.
       */
      expect(actualShape(value), `${key} decoded to the declared ${shape}`).toBe(shape);

      const got = recorded[0];
      const [ns, name] = key.split('.');
      entries.push({
        ns: ns ?? '',
        name: name ?? '',
        http: got?.method ?? '',
        path: templatise(got?.path ?? '', entry?.path ?? ''),
        shape,
      });
    }

    entries.sort((a, b) =>
      a.ns === b.ns ? a.name.localeCompare(b.name) : a.ns.localeCompare(b.ns),
    );
    const expected = [...MANIFEST.entries]
      .map((e) => ({ ns: e.ns, name: e.name, http: e.http, path: e.path, shape: e.shape }))
      .sort((a, b) => (a.ns === b.ns ? a.name.localeCompare(b.name) : a.ns.localeCompare(b.ns)));

    expect(entries).toEqual(expected);

    writeFileSync(
      join(__dirname, '..', 'surface.lock.json'),
      `${JSON.stringify(
        { sdk: 'node', generatedBy: 'src/surface-lock.spec.ts', entries },
        null,
        2,
      )}\n`,
    );
  });

  /**
   * The negative direction: a paginator fed the WRONG shape must fail loudly.
   *
   * The positive test above proves each method copes with the shape this
   * suite says the route sends. It cannot prove the declaration matters — a
   * decoder that ignores the body entirely passes it. This one feeds every
   * auto-paginator a bare array where it expects `{ items, nextCursor }` and
   * requires it to reject, which is exactly the failure the real API handed
   * the .NET and Rust clients on `macros.list`.
   *
   * It is also why `macros.list` has no `listAll` in this SDK, and why
   * `billing.invoices` has no `invoicesAll`: the first has no cursor at all,
   * and the second carries its rows under `data`, so a walker over either
   * could only ever look complete while being wrong.
   */
  it('every auto-paginator rejects a bare array where a page is expected', async () => {
    const recorded: Array<{ method: string; path: string }> = [];
    const chatly = clientAnswering(() => responseForShape('array'), recorded);
    const walkerSet = walkers(chatly);

    // One walker per `page` route, and nothing else — the floor that stops
    // this test quietly shrinking to nothing.
    const pageRoutes = Object.entries(EXPECTED_SHAPE)
      .filter(([, shape]) => shape === 'page')
      .map(([key]) => key);
    expect(Object.keys(walkerSet).sort()).toEqual([...pageRoutes].sort());
    expect(pageRoutes).toHaveLength(EXPECTED_DISTRIBUTION.page);

    for (const [key, walk] of Object.entries(walkerSet)) {
      let threw = false;
      try {
        for await (const _ of walk()) {
          break;
        }
      } catch {
        threw = true;
      }
      expect(threw, `${key}'s paginator accepted a bare array as a page`).toBe(true);
    }
  });

  /**
   * Nothing paginates a route the manifest does not flag.
   *
   * `macros` is the one that mattered — a paginator there raised a decode
   * error on the real bare-array response in two sibling SDKs — and
   * `billing.invoices` is the new one: cursor-paginated under `data`, so a
   * generic walker keyed on `items` would yield an empty first page with a
   * 200 rather than fail.
   */
  it('exposes no walker over a route that is not a page', () => {
    const chatly = clientAnswering(() => responseForShape('object'), []);
    const bag = chatly as unknown as Record<string, Record<string, unknown>>;
    for (const [ns, method] of [
      ['macros', 'listAll'],
      ['billing', 'invoicesAll'],
      ['brands', 'listAll'],
      ['botRoutes', 'listAll'],
      ['customerCards', 'listAll'],
      ['docsSources', 'listAll'],
      ['emailTemplates', 'listAll'],
      ['knowledgeGaps', 'listAll'],
      ['channels', 'listAll'],
    ] as const) {
      expect(
        bag[ns]?.[method],
        `chatly.${ns}.${method} walks a route with no cursor`,
      ).toBeUndefined();
    }
  });
});
